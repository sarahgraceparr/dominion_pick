/**
 * Scores every official recommended kingdom and compares it with random
 * boards drawn from the same sets. Recommended kingdoms were picked by the
 * designers to be fun, so a low percentile points at a gap in our model.
 *
 *   npx tsx scripts/analyze-recommended.ts [report.md]
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { cardsInProducts, getCardByName } from '../src/core/cards';
import { evaluateKingdom, type KingdomLayout } from '../src/core/generator';
import { createRng } from '../src/core/rng';
import type { Card } from '../src/core/types';
import recommended from './data/recommended-kingdoms.json';
import type { RecommendedKingdom } from './import-recommended';

const BASELINE_BOARDS = 150;

const card = (name: string): Card => {
  const c = getCardByName(name);
  if (!c) throw new Error(`unknown card ${name}`);
  return c;
};

export function layoutOf(k: RecommendedKingdom): KingdomLayout {
  return {
    cards: k.cards.map(card),
    landscapes: k.landscapes.map(card),
    extras: k.extras.map(card),
    shelters: k.shelters,
    traits: k.traits.map((t) => ({ trait: card(t.trait), target: card(t.target) })),
  };
}

export interface Analysis {
  kingdom: RecommendedKingdom;
  score: number;
  /** share of random same-set boards this kingdom beats (0–100) */
  percentile: number;
  strategies: string[];
  reasons: string[];
}

/** Random boards from the same products, with the same number of landscapes and the same setup. */
function percentileAgainstRandom(k: RecommendedKingdom, score: number): number {
  const layout = layoutOf(k);
  const products = [...new Set(layout.cards.flatMap((c) => c.products))];
  const pool = cardsInProducts(products).filter((c) => c.kind === 'kingdom');
  const landscapePool = cardsInProducts(products).filter((c) => c.kind === 'landscape' && !c.types.includes('Trait'));
  const rng = createRng(`baseline:${k.name}`);
  let beaten = 0;
  for (let i = 0; i < BASELINE_BOARDS; i++) {
    const cards = rng.shuffle(pool).slice(0, 10);
    const landscapes = rng.shuffle(landscapePool).slice(0, layout.landscapes.length);
    const random = evaluateKingdom({ cards, landscapes, shelters: layout.shelters }).score.total;
    if (score > random) beaten++;
    else if (score === random) beaten += 0.5;
  }
  return Math.round((100 * beaten) / BASELINE_BOARDS);
}

export function analyze(kingdoms: RecommendedKingdom[] = recommended as RecommendedKingdom[]): Analysis[] {
  return kingdoms.map((kingdom) => {
    const { synergies, score } = evaluateKingdom(layoutOf(kingdom));
    return {
      kingdom,
      score: score.total,
      percentile: percentileAgainstRandom(kingdom, score.total),
      strategies: score.archetypes,
      reasons: synergies.slice(0, 3).map((s) => s.reason),
    };
  });
}

export function summarize(results: Analysis[]) {
  const median = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)]!;
  return {
    medianScore: median(results.map((r) => r.score)),
    medianPercentile: median(results.map((r) => r.percentile)),
    belowHalf: results.filter((r) => r.percentile < 50).length,
  };
}

const cell = (s: string) => s.replace(/\|/g, '/');

function report(results: Analysis[]): string {
  const { medianScore, medianPercentile, belowHalf } = summarize(results);
  const bySet = new Map<string, Analysis[]>();
  for (const r of results) {
    const set = r.kingdom.sets.join(' + ');
    bySet.set(set, [...(bySet.get(set) ?? []), r]);
  }
  const row = (r: Analysis) =>
    `| ${cell(r.kingdom.name)} | ${r.score} | ${r.percentile} | ${r.strategies.join(', ')} | ${cell(r.reasons.join('; ') || '—')} |`;
  const header = [
    '| Kingdom | Score | Percentile | Viable strategies | Why it is fun (top synergies) |',
    '| --- | ---: | ---: | --- | --- |',
  ];
  return [
    '# Recommended kingdoms and the fun model',
    '',
    'Generated by `npm run analyze:recommended`. The kingdoms are the official recommendations from the rulebooks,',
    'via the MIT-licensed [dominion-randomizer](https://github.com/blakevanlan/dominion-randomizer) data.',
    '',
    '- **Score**: the fun score the app gives the kingdom (same setup: Shelters, Traits, Allies, Prophecies).',
    '- **Percentile**: share of random boards from the same sets that the kingdom outscores. The designers picked these',
    '  kingdoms to be fun, so a low percentile marks something the model does not understand yet.',
    '',
    `**${results.length} kingdoms. Median score ${medianScore}; median percentile ${medianPercentile}; ${belowHalf} below the 50th percentile.**`,
    '',
    '## Lowest percentiles (where the model needs work)',
    '',
    ...header,
    ...[...results]
      .sort((a, b) => a.percentile - b.percentile)
      .slice(0, 30)
      .map(row),
    '',
    '## All kingdoms by set',
    '',
    ...[...bySet.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .flatMap(([set, rs]) => [`### ${set}`, '', ...header, ...rs.map(row), '']),
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const results = analyze();
  const out = process.argv[2];
  const text = report(results);
  if (out) writeFileSync(out, text);
  console.log(summarize(results));
  for (const r of [...results].sort((a, b) => a.percentile - b.percentile).slice(0, 25)) {
    console.log(
      `${String(r.percentile).padStart(3)}% ${String(r.score).padStart(3)}  ${r.kingdom.name.padEnd(28)} ${r.kingdom.cards.join(', ')} | ${r.kingdom.landscapes.join(', ')}`,
    );
  }
}
